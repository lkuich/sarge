import assert from 'node:assert/strict';
import { readFile, readdir, writeFile } from 'node:fs/promises';

const publicDir = new URL('../public/', import.meta.url);
const files = (await readdir(new URL('docs/', publicDir))).filter((file) => file.endsWith('.md')).sort();
const index = await readFile(new URL('llms.txt', publicDir), 'utf8');
const sections = await Promise.all(files.map(async (file) => {
  assert.ok(index.includes(`/docs/${file}`), `Add ${file} to llms.txt`);
  const content = await readFile(new URL(`docs/${file}`, publicDir), 'utf8');
  return `Source: https://sargetrack.app/docs/${file}\n\n${content.trim()}`;
}));
const bundle = `# Sarge LLM Documentation\n\nComplete public Markdown guides. Generated by \`pnpm --dir www docs:generate\`; edit the source guides in \`www/public/docs/\`.\n\nCanonical index: https://sargetrack.app/llms.txt\n\n---\n\n${sections.join('\n\n---\n\n')}\n`;
const destination = new URL('llms-full.txt', publicDir);

if (process.argv.includes('--check')) {
  assert.equal(await readFile(destination, 'utf8'), bundle, 'LLM bundle is stale. Run pnpm --dir www docs:generate');
} else {
  await writeFile(destination, bundle);
}
